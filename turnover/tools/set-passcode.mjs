/* ============================================================================
 * Sets the console's passcode.   npm run set-passcode -- <code>
 *
 * Writes a salted, iterated hash into src/passcode-config.js — the plaintext
 * is never stored. Run `npm run build` afterwards to publish the change.
 *
 * Pass an empty string to remove the gate entirely:
 *   npm run set-passcode -- ""
 * ========================================================================= */
import { randomBytes } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { sha256Hex } from '../src/sha256.js';

const code = process.argv[2];
if (code === undefined) {
  console.error('usage: npm run set-passcode -- <code>   (empty string removes the gate)');
  process.exit(1);
}

const ITERATIONS = 20000;
let salt = '';
let hash = '';

if (code !== '') {
  salt = randomBytes(16).toString('hex');
  hash = `${salt}:${code}`;
  for (let i = 0; i < ITERATIONS; i += 1) hash = sha256Hex(hash);
}

writeFileSync(
  new URL('../src/passcode-config.js', import.meta.url),
  `/* GENERATED by tools/set-passcode.mjs — do not edit by hand.
 *
 * An empty \`hash\` disables the gate. The plaintext passcode is not stored
 * here or anywhere else in the repository.
 *
 * This is a soft gate on a public static page: see the warning at the top of
 * src/passcode.js before relying on it for anything.
 */
export const PASSCODE = {
  salt: ${JSON.stringify(salt)},
  iterations: ${ITERATIONS},
  hash: ${JSON.stringify(hash)},
};
`
);

console.log(code === '' ? 'Passcode gate REMOVED.' : `Passcode set (${ITERATIONS.toLocaleString()} iterations).`);
console.log('Run `npm run build` to publish the change.');
